"use strict";
const examples = {
  club: {
    prompt: "Сделай одностраничный сайт вымышленного клуба «Переплёт». Цель — объяснить формат встреч. Нужны: заголовок, описание и расписание из трёх придуманных встреч. Используй только вымышленные сведения. Проверь экран телефона. Результат — локальная страница, публикация после моего разрешения.",
    review: "понятен ли формат клуба, читается ли расписание и удобно ли смотреть страницу с телефона."
  },
  budget: {
    prompt: "Составь учебный бюджет пикника на 8 человек с лимитом 8 000 ₽. Придумай цены и явно пометь их как условные. Покажи позиции, количество, общую сумму и остаток. Пересчитай итог. Результат — таблица и короткое пояснение; ничего не покупай.",
    review: "помечены ли цены как условные, сходится ли сумма и укладывается ли план в 8 000 ₽."
  },
  research: {
    prompt: "Сравни три вымышленных формата встреч клуба: прогулка, обсуждение книги и мастерская. Критерии — подготовка, длительность и участие новичков. Отдели придуманные условия от выводов. Результат — компактное сравнение и рекомендация, без реальных персональных данных.",
    review: "сравниваются ли варианты по одним критериям, видны ли допущения и объяснена ли рекомендация."
  }
};
document.querySelectorAll("[data-example]").forEach(button => {
  button.addEventListener("click", () => {
    const example = examples[button.dataset.example];
    document.querySelectorAll("[data-example]").forEach(item => item.setAttribute("aria-pressed", String(item === button)));
    document.getElementById("prompt").textContent = example.prompt;
    document.getElementById("review").textContent = example.review;
  });
});
